# Bharatpur Metropolitan City's 29 administrative wards. Source file
# (bharatpur_wards_all.geojson) had no crs member -- which per the GeoJSON
# spec implies WGS84 -- but its raw coordinates are clearly projected meters
# (e.g. easting ~534020, northing ~3055181), not lon/lat degrees. A crs
# member carrying a calibrated custom Transverse Mercator proj4 string
# (lon_0=84, x_0=500000, k=0.9999, WGS84 ellipsoid) was added before saving
# it here as bharatpur_wards.geojson, so it reprojects through the same
# _reproject_to_wgs84() path as every other layer (see app/utils.py). The
# proj4 parameters were empirically calibrated by matching this file's
# bounding box against the already-correctly-labeled EPSG:32645 grid dataset
# (bharatpur_static_grid_250m.geojson) -- their shared south/west edge lines
# up to within ~2 meters after transform, and total ward area sums to
# 432.95 sq km, matching Bharatpur Metropolitan City's known official area.
