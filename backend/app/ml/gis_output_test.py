"""GIS output testing -- proposal Section 3.13.2: "Predicted High and Danger
zones will be compared with historical flood areas where available. Spatial
overlap may be evaluated using intersection area or Intersection over Union."

What this does: for every dated historical event in dataset/ml_training_dataset_v2.csv
(event_id like "HIST_2008-08-05", 1993-2020, one row per grid per event), runs the
live, deployed model (the same code path GET /api/risk-map uses -- ModelBundle via
app.ml.model_loader, not a bypassed joblib.load like app/ml/evaluate.py) on that
event's actual recorded conditions, and compares the predicted High/Danger grids
against flood_label (this project's per-grid, per-event historical flood ground
truth) using Intersection over Union.

IMPORTANT CAVEAT -- read before citing a headline number in the report:
Most flood_label values here (label_source == "reconstructed", ~96% of rows) were
generated by a formula from the same underlying features/thresholds the model's
training labels were built from, not independent outside evidence. Testing against
those is somewhat circular -- it partly measures whether the model reproduces its
own label-generation rule, not whether it matches independently-verified flood
history. A smaller subset (label_source == "historical_evidence_override", ~4% of
rows) has flood_label from actual outside evidence overriding that formula, which
is the methodologically clean ground truth the proposal is describing.

This script computes IoU across ALL historical rows (both label_source values
combined) as the headline number, per project-owner instruction, but ALSO reports
the override-only subset and the reconstructed-only subset separately so the
circularity concern is visible rather than hidden -- report whichever number(s)
are appropriate with that caveat attached, don't just quote the combined figure
in isolation.

Usage:
    python -m app.ml.gis_output_test
"""

from __future__ import annotations

import json
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import pandas as pd

from app.config import BASE_DIR
from app.ml.evaluate import FEATURE_COLUMNS, RIVER_LEVEL_SCORE_FALLBACK
from app.ml.model_loader import BEST_MODEL_ID, get_model

DATASET_PATH = BASE_DIR / "dataset" / "ml_training_dataset_v2.csv"
RESULTS_PATH = Path(__file__).resolve().parent / "gis_output_test_results.json"

ALERT_CLASSES = {"High", "Danger"}


_READ_CHUNK_ROWS = 200_000


def _load_historical_rows() -> pd.DataFrame:
    """Stream the 1.6GB dataset in chunks, keeping only HIST_* rows, instead
    of loading all 2.59M rows (including the non-historical train/val/test
    rows we don't need here) into memory at once -- the sandbox this was
    developed in has ~3.8GB RAM and a full-frame load OOM-killed the process.
    """
    usecols = ["grid_id", "event_id", "event_time", "flood_label", "label_source", *FEATURE_COLUMNS]
    dtypes = {
        "grid_id": "category",
        "event_id": "string",
        "label_source": "category",
        "flood_label": "int8",
    }
    keep_chunks = []
    for chunk in pd.read_csv(
        DATASET_PATH, usecols=usecols, dtype=dtypes, chunksize=_READ_CHUNK_ROWS, low_memory=False
    ):
        hist_chunk = chunk[chunk["event_id"].str.startswith("HIST_")]
        if len(hist_chunk):
            keep_chunks.append(hist_chunk.copy())

    hist = pd.concat(keep_chunks, ignore_index=True)
    hist["river_level_score"] = hist["river_level_score"].fillna(RIVER_LEVEL_SCORE_FALLBACK)
    return hist


_CHUNK_SIZE = 50_000


def _score_subset(hist: pd.DataFrame, bundle: Any) -> dict[str, Any]:
    """Run the live model on `hist` and compute IoU/precision/recall of
    predicted High/Danger grids against flood_label.

    Runs in chunks (via bundle.predict_batch, the same code path GET
    /api/risk-map uses) rather than converting all rows to dicts at once --
    this dataset has ~1.7M historical rows and the sandbox this was developed
    in only has ~3.8GB RAM, so an all-at-once dict conversion OOM-killed the
    process. Chunking keeps peak memory bounded without changing the model
    or the inference path at all.
    """
    if len(hist) == 0:
        return {"row_count": 0}

    tp = fp = fn = tn = 0
    actual_flooded_full = hist["flood_label"].astype(int) == 1
    features = hist[FEATURE_COLUMNS]

    for start in range(0, len(hist), _CHUNK_SIZE):
        chunk_features = features.iloc[start : start + _CHUNK_SIZE]
        feature_rows = chunk_features.to_dict(orient="records")
        predictions = bundle.predict_batch(feature_rows)
        predicted_alert = pd.Series(
            [p["predicted_risk_class"] in ALERT_CLASSES for p in predictions],
            index=chunk_features.index,
        )
        actual_flooded = actual_flooded_full.loc[chunk_features.index]

        tp += int((predicted_alert & actual_flooded).sum())
        fp += int((predicted_alert & ~actual_flooded).sum())
        fn += int((~predicted_alert & actual_flooded).sum())
        tn += int((~predicted_alert & ~actual_flooded).sum())

    union = tp + fp + fn
    iou = round(tp / union, 4) if union else None
    precision = round(tp / (tp + fp), 4) if (tp + fp) else None
    recall = round(tp / (tp + fn), 4) if (tp + fn) else None

    return {
        "row_count": len(hist),
        "event_count": int(hist["event_id"].nunique()),
        "true_positive": tp,
        "false_positive": fp,
        "false_negative": fn,
        "true_negative": tn,
        "intersection_over_union": iou,
        "precision": precision,
        "recall": recall,
    }


def main() -> None:
    start = time.monotonic()
    print(f"Loading historical event rows from {DATASET_PATH.relative_to(BASE_DIR)} ...")
    hist = _load_historical_rows()
    print(f"  {len(hist):,} rows across {hist['event_id'].nunique()} historical events (1993-2020)")

    override = hist[hist["label_source"] == "historical_evidence_override"]
    reconstructed = hist[hist["label_source"] == "reconstructed"]
    print(
        f"  {len(override):,} rows with independently-evidenced flood_label "
        f"(historical_evidence_override), {len(reconstructed):,} rows with "
        f"formula-reconstructed flood_label"
    )

    print(f"Scoring with the live {BEST_MODEL_ID} model (app.ml.model_loader, same path GET /api/risk-map uses) ...")
    bundle = get_model(BEST_MODEL_ID)

    results = {
        "combined_all_historical_rows": _score_subset(hist, bundle),
        "historical_evidence_override_only": _score_subset(override, bundle),
        "reconstructed_only": _score_subset(reconstructed, bundle),
    }

    elapsed = time.monotonic() - start
    print(f"\nDone in {elapsed:.1f}s.\n")

    for label, r in results.items():
        print(f"-- {label} --")
        if r.get("row_count"):
            print(
                f"  rows={r['row_count']:,} events={r['event_count']} "
                f"TP={r['true_positive']:,} FP={r['false_positive']:,} "
                f"FN={r['false_negative']:,} TN={r['true_negative']:,}"
            )
            print(
                f"  IoU={r['intersection_over_union']}  precision={r['precision']}  "
                f"recall={r['recall']}"
            )
        else:
            print("  (no rows)")
        print()

    output = {
        "computed_at": datetime.now(timezone.utc).isoformat(),
        "elapsed_seconds": round(elapsed, 1),
        "model_id": BEST_MODEL_ID,
        "dataset_path": str(DATASET_PATH.relative_to(BASE_DIR)),
        "methodology_note": (
            "combined_all_historical_rows is the headline number per project-owner "
            "instruction, but includes ~96% formula-reconstructed flood_label rows "
            "(label_source == 'reconstructed'), which is somewhat circular against a "
            "model trained on similar features/thresholds. "
            "historical_evidence_override_only is the methodologically clean subset "
            "(independently-evidenced flood_label) -- see this module's docstring."
        ),
        "results": results,
    }
    RESULTS_PATH.write_text(json.dumps(output, indent=2) + "\n")
    print(f"Wrote {RESULTS_PATH.relative_to(BASE_DIR)}")


if __name__ == "__main__":
    main()
